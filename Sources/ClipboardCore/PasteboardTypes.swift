import Foundation

/// Raw pasteboard type identifiers the app cares about. Kept as plain strings so
/// the core module stays free of AppKit and is easy to unit test.
public enum PBType {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"

    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"

    /// Text representations we store, in the order they're written back on paste.
    public static let textTypes = [plainText, rtf, html, url]
    /// Image representations in order of preference. Only the first present one is stored.
    public static let imageTypes = [png, tiff, jpeg, heic]

    /// nspasteboard.org markers. Any of these present means "do not record".
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let legacyOnePassword = "com.agilebits.onepassword"
    public static let sensitiveMarkers: [String] = [concealed, transient, autoGenerated, legacyOnePassword]

    /// nspasteboard.org marker whose string value is the bundle ID of the app that wrote the data.
    public static let source = "org.nspasteboard.source"

    public static let finderBundleID = "com.apple.finder"
}
